  /**
   * الحصول على الكلمات المشابهة لكلمة معينة
   * @param {string} word - الكلمة المراد البحث عن مشابهاتها
   * @returns {Array} - مصفوفة الكلمات المشابهة
   */
  getSynonyms(word) {
    // البحث المباشر
    if (this.synonyms[word]) {
      return this.synonyms[word];
    }

    // البحث العكسي (إذا كانت الكلمة موجودة كمرادف)
    for (const [key, synonyms] of Object.entries(this.synonyms)) {
      if (synonyms.includes(word)) {
        return [key, ...synonyms];
      }
    }

    return [word];
  }

  /**
   * توسيع الاستعلام باستخدام الكلمات المشابهة
   * @param {string} query - الاستعلام الأصلي
   * @returns {Array} - مصفوفة الكلمات الموسعة
   */
  expandQuery(query) {
    const words = query.split(/\s+/).filter(w => w.length > 2);
    const expandedWords = new Set();

    words.forEach(word => {
      expandedWords.add(word);
      const synonyms = this.getSynonyms(word);
      synonyms.forEach(synonym => {
        expandedWords.add(synonym);
      });
    });

    return Array.from(expandedWords);
  }

  /**
   * البحث الدلالي في النص
   * @param {string} text - النص المراد البحث فيه
   * @param {string} query - الاستعلام
   * @returns {boolean} - هل النص يحتوي على كلمات مشابهة للاستعلام
   */
  semanticSearch(text, query) {
    const expandedQuery = this.expandQuery(query);
    const lowerText = text.toLowerCase();

    return expandedQuery.some(word => 
      lowerText.includes(word.toLowerCase())
    );
  }
